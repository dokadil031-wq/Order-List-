                                    label = { Text("Email Address or Mobile Number") },
                                    shape = MaterialTheme.shapes.medium,
                                    modifier = Modifier.fillMaxWidth().onFocusChanged { if (it.isFocused && email.isEmpty()) loginDropdownExpanded = true },
