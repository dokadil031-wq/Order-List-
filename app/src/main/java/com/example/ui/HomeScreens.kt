                        }
    
                        if (!isCreateAccount) {
                            TextButton(onClick = { 
                                isForgotPassword = true 
                                fpMessage = ""
                                fpEmailOrPhone = ""
                                fpNewPassword = ""
                            }) {
                                Text("Forgot password?")
                            }
                        }
                    }
                }
            }
        }
    }

    LaunchedEffect(fpStage, fpEmailOrPhone) {
        if (fpStage == 2) {
            fpOtpGenerated = "123456"
            fpOtpEntered = fpOtpGenerated
        }
    }

    if (isForgotPassword) {
        AlertDialog(
            onDismissRequest = { isForgotPassword = false; fpStage = 1; fpMessage = "" },
