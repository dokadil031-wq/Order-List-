                                                    override fun onVerificationCompleted(credential: com.google.firebase.auth.PhoneAuthCredential) {
                                                        com.google.firebase.auth.FirebaseAuth.getInstance().signInWithCredential(credential).addOnCompleteListener { task ->
                                                            if (task.isSuccessful) {
                                                                viewModel.handlePhoneAuthSuccess(phone = currentPhone, name = "", pass = password, shopName = "", isRegister = false) { success, msg ->
                                                                    isLoading = false
                                                                    if (!success) errorMessage = msg else isOtpVerification = false
                                                                }
                                                            } else {
                                                                isLoading = false
                                                                errorMessage = "Auto-verification failed: ${task.exception?.localizedMessage}"
                                                            }
                                                        }
