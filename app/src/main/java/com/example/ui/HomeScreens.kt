                                                if (!success) errorMessage = msg
                                            }
                                        }
                                    } else {
                                        errorMessage = "Please fill all required fields (Shop Name is optional for buyers)"
                                    }
                                } else {
                                    if (email.isNotBlank() && password.isNotBlank()) {
                                        if (isPhoneLogin) {
                                            if (activity == null) { errorMessage = "Activity issue"; return@Button }
                                            isLoading = true
                                            val formattedPhone = if (currentPhone.startsWith("+")) currentPhone else "+91$currentPhone"
