                                                        isLoading = false
                                                        val msg = e.localizedMessage ?: ""
                                                        if (msg.contains("API key not valid", ignoreCase = true) || msg.contains("API_KEY_INVALID", ignoreCase = true)) {
                                                            errorMessage = "Firebase Configuration Error: API Key not valid. Please upload a real google-services.json file via AI Studio."
                                                        } else {
                                                            errorMessage = "Verification failed: $msg"
                                                        }
                                                    }
                                                    override fun onCodeSent(vId: String, token: com.google.firebase.auth.PhoneAuthProvider.ForceResendingToken) {
                                                        isLoading = false
                                                        verificationId = vId
                                                        isOtpVerification = true
                                                    }
                                                }).build()
                                            com.google.firebase.auth.PhoneAuthProvider.verifyPhoneNumber(options)
                                        } else {
                                            isLoading = true
                                            viewModel.loginUser(email, password) { success, msg ->
                                                isLoading = false
                                                if (!success) errorMessage = msg
                                            }
                                        }
                                    } else {
                                        errorMessage = "Please enter email/mobile and password"
                                    }
                                }
                            },
                            shape = MaterialTheme.shapes.medium,
                            modifier = Modifier.fillMaxWidth().height(48.dp),
                            enabled = !isLoading
                        ) {
                            if (isLoading) {
                                androidx.compose.material3.CircularProgressIndicator(modifier = Modifier.size(24.dp), color = MaterialTheme.colorScheme.onPrimary)
                            } else {
                                Text(if (isCreateAccount) "Create Account" else "Login")
                            }
                        }
                        
