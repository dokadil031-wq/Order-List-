                                    Icon(Icons.Default.CheckCircle, contentDescription = "Verified", tint = androidx.compose.ui.graphics.Color.Green)
                                }
                            }
                        )
                    } else if (fpStage == 3) {
                        OutlinedTextField(
                            value = fpNewPassword,
                            onValueChange = { fpNewPassword = it },
                            label = { Text("New Password") },
                            singleLine = true,
                            visualTransformation = PasswordVisualTransformation(),
                            modifier = Modifier.fillMaxWidth()
                        )
                    }
                    
                    if (fpMessage.isNotEmpty()) {
                        Spacer(modifier = Modifier.height(8.dp))
                        Text(
                            text = fpMessage,
                            color = if (fpIsError) MaterialTheme.colorScheme.error else MaterialTheme.colorScheme.primary,
                            style = MaterialTheme.typography.bodySmall
                        )
                    }
                }
            },
            confirmButton = {
                Button(
                    onClick = {
                        fpMessage = ""
                        fpIsError = false
                        if (fpStage == 1) {
                            if (fpEmailOrPhone.isNotBlank()) {
                                fpStage = 3
                            } else {
                                fpIsError = true
                                fpMessage = "Please enter email or phone"
                            }
                        } else if (fpStage == 2) {
                            if (fpOtpEntered == fpOtpGenerated) {
                                fpStage = 3
                            } else {
                                fpIsError = true
                                fpMessage = "Invalid OTP"
                            }
                        } else if (fpStage == 3) {
                            if (fpNewPassword.isNotBlank()) {
                                isLoading = true
                                viewModel.resetPassword(fpEmailOrPhone, fpNewPassword) { success, msg ->
                                    isLoading = false
                                    fpIsError = !success
                                    fpMessage = msg
                                    if (success) {
                                        android.widget.Toast.makeText(context, msg, android.widget.Toast.LENGTH_SHORT).show()
                                        isForgotPassword = false
                                        fpStage = 1
                                    }
                                }
                            } else {
                                fpIsError = true
                                fpMessage = "Please enter a new password"
                            }
                        }
                    },
                    enabled = !isLoading
                ) {
                    if (isLoading) {
                        androidx.compose.material3.CircularProgressIndicator(modifier = Modifier.size(16.dp), color = MaterialTheme.colorScheme.onPrimary)
                    } else {
                        Text(if (fpStage == 1) "Next" else if (fpStage == 2) "Verify" else "Reset")
                    }
                }
            },
            dismissButton = {
                TextButton(onClick = { 
                    if (fpStage > 1 && !isLoading && fpStage != 3) {
                        fpStage--
                        fpMessage = ""
                    } else {
                        isForgotPassword = false 
                        fpStage = 1
                    }
                }) {
                    Text(if (fpStage == 2) "Back" else "Cancel")
                }
            }
        )
    }
